#!/usr/bin/env python3
"""Export verified supplementary profiles without changing paper L/M/H."""
from copy import deepcopy
import hashlib
import json
from pathlib import Path

HERE=Path(__file__).resolve().parent
ROOT=HERE.parent

def main():
    selected=ROOT/'results/extended-classical128/selected.json'
    data=json.loads(selected.read_text());assert data['status']=='verified'
    selection_digest=hashlib.sha256(selected.read_bytes()).hexdigest()
    integers=('logQ','logM','k','ell','q_bits','base','length','source_v_bits','re_u_bits','re_v_bits','source_eta','internal_eta','terminal_eta')
    strings=('source_std','pad_std','sigma_source','sigma_pad')
    runtime=[]
    for name,item in data['profiles'].items():
        assert item['status'] in ('verified','verified-existing-frozen')
        r=deepcopy(item['runtime']);r['name']=name;runtime.append(r)
    # Bind public contexts to the actual numeric constants, not to elapsed
    # verification times or cached-estimator metadata.
    fields=('name',)+integers+('q',)+strings+('sigma_terminal',)
    constants=[{key:r.get(key) for key in fields} for r in runtime]
    digest=hashlib.sha256(json.dumps(constants,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    code=['/* Generated by params/export_extended.py from verified supplementary profiles. */',
          '#define LBPRE_EXTRA_SOURCE_SHA256 '+json.dumps(digest),
          'static const lbpre_params extended_sets[] = {']
    expected=['/* Generated from the same selected.json; default benchmark remains L/M/H. */',
              '#define LBPRE_EXTRA_SOURCE_SHA256 '+json.dumps(digest)]
    for r in runtime:
        parts=['.name='+json.dumps(r['name'])]
        parts.extend('.%s=%d'%(key,r[key]) for key in integers)
        parts.append('.q=UINT64_C(%d)'%r['q'])
        parts.extend('.%s=%s'%(key,json.dumps(r[key])) for key in strings)
        parts.append('.sigma_terminal=NULL')
        code.append('    { '+', '.join(parts)+' },')
        s=r['sizes_bytes'];matrix=r['k']*r['ell']*32*r['q_bits']
        expected.append('    {%d, %d, UINT64_C(%d), %d, %d, %d, %d, %d, %d, %s},'%(
          r['logQ'],r['base'],r['q'],s['public_key_bytes'],s['secret_key_bytes'],matrix,
          s['rekey_bytes'],s['source_ct_bytes'],s['reenc_ct_bytes'],json.dumps(r['name'])))
    code.append('};')
    (ROOT/'latpre/src/extended_params.inc').write_text('\n'.join(code)+'\n')
    (ROOT/'latpre/bench/extended_expected.inc').write_text('\n'.join(expected)+'\n')
    manifest={'profile_id':'LATPRE-CLASSICAL128-SUPPLEMENT-v1','parameter_sha256':digest,
      'selection_file_sha256':selection_digest,'source':'../results/extended-classical128/selected.json',
      'generated_parameters':runtime,'frozen_LMH_unchanged':True,
      'gaussian_sampler':'OpenFHE-style CDF/Karney; integer-assisted wide-mask proposals',
      'sampling_error_bound_certified':False}
    current_manifest=ROOT/'latpre/EXTENDED_PARAMETER_SOURCE.json'
    snapshots=ROOT/'results/extended-classical128/implementation-manifests'
    snapshots.mkdir(exist_ok=True)
    if current_manifest.exists():
        previous=json.loads(current_manifest.read_text())
        (snapshots/(previous['parameter_sha256']+'.json')).write_bytes(current_manifest.read_bytes())
    current_manifest.write_text(json.dumps(manifest,indent=2)+'\n')
    (snapshots/(digest+'.json')).write_bytes(current_manifest.read_bytes())
    (HERE/'extended_profiles.json').write_text(json.dumps({'schema':'latpre-supplementary-profiles-v1',
      'profile_id':manifest['profile_id'],'parameter_sha256':digest,'selected_sha256':selection_digest,
      'profiles':data['profiles']},indent=2)+'\n')
    print('Exported '+', '.join(data['profiles']))

if __name__=='__main__':main()
